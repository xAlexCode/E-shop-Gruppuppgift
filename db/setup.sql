-- ---------------------------------------------------------------------------
-- Tabeller (se docs/ER.md)
-- ---------------------------------------------------------------------------

create table producers (
  id int generated by default as identity primary key,
  name text not null unique,
  country text not null
);

create table products (
  id int generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  type text not null check (type in ('rott', 'vitt', 'rose', 'mousserande', 'dessert', 'orange', 'alkoholfritt')),
  producer_id int not null references producers (id) on delete restrict,
  country text not null,
  region text,
  grape text,
  vintage int,
  price int not null check (price > 0),
  volume_ml int not null check (volume_ml > 0),
  alcohol numeric(3, 1),
  body int check (body between 1 and 5),
  sweetness int check (sweetness between 1 and 5),
  tannin int check (tannin between 1 and 5),
  acidity int check (acidity between 1 and 5),
  food_pairing text,
  description text not null,
  image_url text not null,
  created_at timestamptz not null default now()
);

create table profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);

create table orders (
  id uuid primary key default gen_random_uuid(),
  order_number int generated always as identity (start with 1001) unique,
  user_id uuid references auth.users (id) on delete set null,
  name text not null,
  email text not null,
  street text not null,
  postal_code text not null check (postal_code ~ '^[0-9]{5}$'),
  city text not null,
  payment_method text not null check (payment_method in ('kort', 'faktura', 'swish')),
  shipping int not null default 59,
  total int not null,
  status text not null default 'mottagen',
  created_at timestamptz not null default now()
);

create table order_items (
  id int generated by default as identity primary key,
  order_id uuid not null references orders (id) on delete cascade,
  product_id int not null references products (id) on delete restrict,
  quantity int not null check (quantity between 1 and 12),
  unit_price int not null check (unit_price > 0)
);

create table favorites (
  user_id uuid not null references auth.users (id) on delete cascade,
  product_id int not null references products (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table reviews (
  id int generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  product_id int not null references products (id) on delete cascade,
  rating int not null check (rating between 1 and 5),
  text text check (char_length(text) <= 1000),
  created_at timestamptz not null default now(),
  unique (user_id, product_id)
);

-- Row level security på, utan policies: webbläsaren når inga tabeller direkt.
-- All åtkomst går via servern och lib/db.ts.
alter table producers enable row level security;
alter table products enable row level security;
alter table profiles enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;
alter table favorites enable row level security;
alter table reviews enable row level security;

